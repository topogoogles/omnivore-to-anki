"""Structured Markdown study guide exporter."""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path

from src.core.schemas import AnkiCard, ExtractionStep


class MarkdownExporter:
    """Compiles extracted assertions and flashcards into a Markdown study summary."""

    def __init__(self, deck_name: str = "Omnivore::AutoGenerated") -> None:
        self.deck_name = deck_name

    def export_to_file(
        self,
        assertions: list[ExtractionStep],
        cards: list[AnkiCard],
        output_path: str | Path,
        thought_process: str = "",
    ) -> Path:
        """Render a formatted Markdown study guide to disk."""
        target = Path(output_path)
        target.parent.mkdir(parents=True, exist_ok=True)
        timestamp = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")

        lines = [
            f"# Study Guide: {self.deck_name}",
            f"*Generated on {timestamp}*",
            "",
        ]

        if thought_process:
            lines.extend(
                [
                    "## Synthesis Overview",
                    f"> {thought_process}",
                    "",
                ]
            )

        if assertions:
            lines.append("## Core Extracted Assertions")
            for idx, item in enumerate(assertions, start=1):
                lines.extend(
                    [
                        f"### {idx}. {item.core_assertion}",
                        f"- **Source Grounding:** *\"{item.source_quote}\"*",
                        f"- **Retrieval Utility:** {item.why_retrieval_matters}",
                        "",
                    ]
                )

        if cards:
            lines.append("## Active Recall Flashcards")
            for card in cards:
                tags_str = ", ".join(f"`{t}`" for t in card.tags)
                lines.extend(
                    [
                        f"### [{card.card_type.value.upper()}] {card.front}",
                        f"- **Answer:** {card.back}",
                        f"- **Domain:** `{card.domain.value}` | **Difficulty:** {card.difficulty_score}/5",
                        f"- **Tags:** {tags_str}",
                    ]
                )
                if card.extra_context:
                    lines.append(f"- **Extra Context:** {card.extra_context}")
                lines.append("")

        target.write_text("\n".join(lines), encoding="utf-8")
        return target