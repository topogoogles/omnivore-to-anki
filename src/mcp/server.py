"""FastMCP server exposing Omnivore-to-Anki tools over stdio or SSE."""

from __future__ import annotations

from typing import Any

from mcp.server.fastmcp import FastMCP

from src.agents.graph import autoanki_graph
from src.mcp.tools.anki_connect import AnkiConnectClient
from src.mcp.tools.transcript import fetch_source_transcript

mcp = FastMCP("Omnivore-to-Anki")


@mcp.tool()
async def extract_media_transcript(source: str) -> dict[str, Any]:
    """Extract cleaned transcript text from a YouTube URL, PDF path, or audio file."""
    return fetch_source_transcript(source)


@mcp.tool()
async def generate_anki_deck_from_source(
    source: str,
    deck_name: str = "Omnivore::AutoGenerated",
    max_retries: int = 2,
) -> dict[str, Any]:
    """Ingest a URL, PDF, audio file, or raw text and generate verified Anki flashcards."""
    ingested = fetch_source_transcript(source)
    initial_state = {
        "raw_text": ingested["raw_text"],
        "deck_name": deck_name,
        "metadata": {"ingestion_method": ingested.get("ingestion_method", "unknown")},
        "max_retries": max_retries,
    }

    final_state = await autoanki_graph.ainvoke(initial_state)
    cards = final_state.get("final_cards", [])

    return {
        "deck_name": deck_name,
        "card_count": len(cards),
        "export_summary": final_state.get("export_summary"),
        "cards": [c.model_dump() for c in cards],
    }


@mcp.tool()
async def check_anki_desktop_status() -> dict[str, Any]:
    """Ping local AnkiConnect instance to verify if Anki desktop is running."""
    client = AnkiConnectClient()
    online = await client.ping()
    return {"anki_connect_online": online, "url": client.base_url}