"""AnkiConnect HTTP client for syncing flashcards directly to Anki desktop."""

from __future__ import annotations

import logging
from typing import Any

import httpx

from src.core.exceptions import SyncError
from src.core.schemas import AnkiCard, CardType

logger = logging.getLogger(__name__)

DEFAULT_ANKI_CONNECT_URL = "http://127.0.0.1:8765"


class AnkiConnectClient:
    """Async wrapper around AnkiConnect REST API."""

    def __init__(self, base_url: str = DEFAULT_ANKI_CONNECT_URL, timeout: float = 10.0) -> None:
        self.base_url = base_url
        self.timeout = timeout

    async def _invoke(self, action: str, **params: Any) -> Any:
        """Send a JSON-RPC style payload to the AnkiConnect endpoint."""
        payload = {"action": action, "version": 6, "params": params}
        try:
            async with httpx.AsyncClient(timeout=self.timeout) as client:
                response = await client.post(self.base_url, json=payload)
                response.raise_for_status()
                data = response.json()
        except httpx.ConnectError as err:
            raise SyncError(
                f"Could not connect to AnkiConnect at {self.base_url}. "
                "Ensure Anki desktop is open and the AnkiConnect add-on is installed."
            ) from err
        except httpx.HTTPError as err:
            raise SyncError(f"HTTP communication error with AnkiConnect: {err}") from err

        if len(data) != 2:
            raise SyncError("Invalid response structure received from AnkiConnect.")
        if "error" not in data or "result" not in data:
            raise SyncError("Response missing required 'error' or 'result' keys from AnkiConnect.")
        if data["error"]:
            raise SyncError(f"AnkiConnect API error: {data['error']}")

        return data["result"]

    async def ping(self) -> bool:
        """Check if AnkiConnect is accessible and responding."""
        try:
            version = await self._invoke("version")
            return version >= 6
        except SyncError:
            return False

    async def ensure_deck(self, deck_name: str) -> None:
        """Create target deck if it does not already exist."""
        await self._invoke("createDeck", deck=deck_name)

    def _convert_card_to_note(self, card: AnkiCard, deck_name: str) -> dict[str, Any]:
        """Map internal AnkiCard schema to an AnkiConnect note dictionary."""
        is_cloze = card.card_type == CardType.CLOZE
        model_name = "Cloze" if is_cloze else "Basic"

        if is_cloze:
            fields = {
                "Text": card.front,
                "Back Extra": f"{card.back}<br><br><small>{card.extra_context}</small>"
                if card.extra_context
                else card.back,
            }
        else:
            back_content = card.back
            if card.extra_context:
                back_content += f"<br><br><small><em>{card.extra_context}</em></small>"
            fields = {
                "Front": card.front,
                "Back": back_content,
            }

        return {
            "deckName": deck_name,
            "modelName": model_name,
            "fields": fields,
            "tags": card.tags,
            "options": {
                "allowDuplicate": False,
                "duplicateScope": "deck",
            },
        }

    async def sync_cards(
        self, cards: list[AnkiCard], deck_name: str = "Omnivore::AutoGenerated"
    ) -> dict[str, Any]:
        """Push a list of AnkiCard items into Anki via canAddNotes and addNotes."""
        if not cards:
            return {"added": 0, "skipped": 0, "errors": []}

        await self.ensure_deck(deck_name)
        notes = [self._convert_card_to_note(c, deck_name) for c in cards]

        can_add_flags: list[bool] = await self._invoke("canAddNotes", notes=notes)
        notes_to_add = [note for note, can_add in zip(notes, can_add_flags) if can_add]
        skipped_count = len(notes) - len(notes_to_add)

        if not notes_to_add:
            logger.info("All %d notes are duplicates or invalid; skipping addNotes.", len(notes))
            return {"added": 0, "skipped": skipped_count, "errors": []}

        results: list[int | None] = await self._invoke("addNotes", notes=notes_to_add)

        added_ids = [res for res in results if res is not None]
        errors = [f"Failed to insert note index {idx}" for idx, res in enumerate(results) if res is None]

        return {
            "added": len(added_ids),
            "skipped": skipped_count,
            "errors": errors,
            "note_ids": added_ids,
        }