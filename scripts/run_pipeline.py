"""End-to-end CLI runner for the Omnivore-to-Anki pipeline."""

from __future__ import annotations

import argparse
import asyncio
import logging
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from dotenv import load_dotenv

from src.agents.graph import autoanki_graph
from src.export.markdown import MarkdownExporter
from src.mcp.tools.transcript import fetch_source_transcript
from src.storage.connection import get_db_session, init_db
from src.storage.repository import StorageRepository

load_dotenv()

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
)
logger = logging.getLogger("run_pipeline")


async def execute_pipeline(
    source: str,
    deck_name: str,
    force_refresh: bool = False,
    max_retries: int = 2,
) -> None:
    """Run ingestion, SQLite deduplication check, LangGraph generation, and Markdown export."""
    init_db()

    logger.info("Ingesting source: %s", source)
    ingested = fetch_source_transcript(source)
    raw_text = ingested["raw_text"]
    method = ingested.get("ingestion_method", "unknown")

    with get_db_session() as session:
        repo = StorageRepository(session)
        if not force_refresh and repo.is_chunk_processed(raw_text):
            cached_cards = repo.get_cards_by_chunk(raw_text)
            logger.info(
                "Source chunk already processed in SQLite (%d cards cached). Use --force to regenerate.",
                len(cached_cards),
            )
            for c in cached_cards:
                print(f"[{c.card_type.value.upper()}] Q: {c.front} -> A: {c.back}")
            return

    logger.info("Running Perplexity CoT LangGraph pipeline...")
    initial_state = {
        "raw_text": raw_text,
        "deck_name": deck_name,
        "metadata": {"source": source, "ingestion_method": method},
        "max_retries": max_retries,
    }

    final_state = await autoanki_graph.ainvoke(initial_state)
    final_cards = final_state.get("final_cards", [])
    assertions = final_state.get("extracted_assertions", [])
    export_summary = final_state.get("export_summary", {})

    with get_db_session() as session:
        repo = StorageRepository(session)
        if not repo.is_chunk_processed(raw_text):
            repo.save_processed_chunk(
                source_identifier=source,
                source_type=method,
                raw_text=raw_text,
                cards=final_cards,
                is_synced=(export_summary.get("status") == "synced_via_ankiconnect"),
            )

    md_exporter = MarkdownExporter(deck_name=deck_name)
    safe_name = deck_name.replace("::", "_").lower()
    md_path = md_exporter.export_to_file(
        assertions=assertions,
        cards=final_cards,
        output_path=f"data/cache/{safe_name}_notes.md",
        thought_process=final_state.get("thought_process", ""),
    )

    print("\n==========================================")
    print(f"Pipeline Complete! Generated {len(final_cards)} verified cards.")
    print(f"Export Summary : {export_summary}")
    print(f"Markdown Notes : {md_path}")
    print("==========================================\n")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Omnivore-to-Anki: Convert URLs, PDFs, or notes into atomic Anki decks."
    )
    parser.add_argument(
        "--source",
        type=str,
        default=(
            "In PostgreSQL, Write-Ahead Logging (WAL) ensures data integrity by writing "
            "changes to a transaction log before flushing dirty pages to disk. Checkpoint "
            "processes periodically flush WAL segments to data files."
        ),
        help="YouTube URL, PDF file path, audio file path, or raw text snippet.",
    )
    parser.add_argument(
        "--deck",
        type=str,
        default="Omnivore::AutoGenerated",
        help="Target Anki deck name (e.g., 'Systems::PostgreSQL').",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Bypass SQLite deduplication cache and force regeneration.",
    )
    args = parser.parse_args()
    asyncio.run(execute_pipeline(args.source, args.deck, args.force))


if __name__ == "__main__":
    main()